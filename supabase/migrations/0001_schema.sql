alter table public.buyer enable row level security;
alter table public.product enable row level security;
alter table public.cart enable row level security;
alter table public.cart_item enable row level security;
alter table public.orders enable row level security;
alter table public.order_item enable row level security;
alter table public.conversations enable row level security;
alter table public.messages enable row level security;
alter table public.notifications enable row level security;

-- --- seller ---
create policy "seller read own" on public.seller for select using (auth.uid() = seller_id);
create policy "seller insert own" on public.seller for insert with check (auth.uid() = seller_id);
create policy "seller update own" on public.seller for update using (auth.uid() = seller_id);

-- --- buyer ---
create policy "buyer read own" on public.buyer for select using (auth.uid() = buyer_id);
create policy "buyer insert own" on public.buyer for insert with check (auth.uid() = buyer_id);
create policy "buyer update own" on public.buyer for update using (auth.uid() = buyer_id);

-- --- product: public read, owners manage ---
create policy "product public read" on public.product for select using (true);
create policy "product seller insert" on public.product for insert with check (auth.uid() = seller_id);
create policy "product seller update" on public.product for update using (auth.uid() = seller_id);
create policy "product seller delete" on public.product for delete using (auth.uid() = seller_id);

-- --- cart: owner only ---
create policy "cart owner select" on public.cart for select using (auth.uid() = buyer_id);
create policy "cart owner insert" on public.cart for insert with check (auth.uid() = buyer_id);
create policy "cart owner update" on public.cart for update using (auth.uid() = buyer_id);
create policy "cart owner delete" on public.cart for delete using (auth.uid() = buyer_id);

-- --- cart_item: via owning cart ---
create policy "cart_item select via cart" on public.cart_item for select
  using (exists (select 1 from public.cart c where c.cart_id = cart_item.cart_id and c.buyer_id = auth.uid()));
create policy "cart_item insert via cart" on public.cart_item for insert
  with check (exists (select 1 from public.cart c where c.cart_id = cart_item.cart_id and c.buyer_id = auth.uid()));
create policy "cart_item update via cart" on public.cart_item for update
  using (exists (select 1 from public.cart c where c.cart_id = cart_item.cart_id and c.buyer_id = auth.uid()));
create policy "cart_item delete via cart" on public.cart_item for delete
  using (exists (select 1 from public.cart c where c.cart_id = cart_item.cart_id and c.buyer_id = auth.uid()));

-- --- orders: buyer owns; seller managing own products ---
create policy "orders buyer select" on public.orders for select
  using (auth.uid() = buyer_id);
create policy "orders buyer insert" on public.orders for insert with check (auth.uid() = buyer_id);
create policy "orders seller select" on public.orders for select
  using (exists (select 1 from public.order_item oi
                 join public.product p on p.product_id = oi.product_id
                 where oi.order_id = orders.order_id and p.seller_id = auth.uid()));
create policy "orders seller update status" on public.orders for update
  using (exists (select 1 from public.order_item oi
                 join public.product p on p.product_id = oi.product_id
                 where oi.order_id = orders.order_id and p.seller_id = auth.uid()));

-- --- order_item: buyer via order; seller via product ---
create policy "order_item buyer select" on public.order_item for select
  using (exists (select 1 from public.orders o where o.order_id = order_item.order_id and o.buyer_id = auth.uid()));
create policy "order_item seller select" on public.order_item for select
  using (exists (select 1 from public.product p where p.product_id = order_item.product_id and p.seller_id = auth.uid()));
create policy "order_item buyer insert" on public.order_item for insert
  with check (exists (select 1 from public.orders o where o.order_id = order_item.order_id and o.buyer_id = auth.uid()));

-- --- conversations: participants only ---
create policy "conversation select participant" on public.conversations for select
  using (auth.uid() = buyer_id or auth.uid() = seller_id);
create policy "conversation insert buyer" on public.conversations for insert
  with check (auth.uid() = buyer_id);
create policy "conversation insert seller" on public.conversations for insert
  with check (auth.uid() = seller_id);

-- --- messages: participants of conversation only ---
create policy "message select participant" on public.messages for select
  using (exists (select 1 from public.conversations c
                 where c.id = messages.conversation_id
                 and (c.buyer_id = auth.uid() or c.seller_id = auth.uid())));
create policy "message insert participant" on public.messages for insert
  with check (exists (select 1 from public.conversations c
                      where c.id = messages.conversation_id
                      and (c.buyer_id = auth.uid() or c.seller_id = auth.uid())));

-- --- notifications: owner only ---
create policy "notification owner select" on public.notifications for select
  using (auth.uid() = user_id);
create policy "notification owner update" on public.notifications for update
  using (auth.uid() = user_id);
create policy "notification owner delete" on public.notifications for delete
  using (auth.uid() = user_id);