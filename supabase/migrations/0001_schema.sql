-- UP Cloth Market — PostgreSQL schema for Supabase
-- Created from the MySQL ER schema + chat & notification tables
-- Run this entire file in the Supabase SQL Editor (one execution).

create extension if not exists pgcrypto;

-- ============================================================================
-- USERS (auth.users references) — buyer & seller kept separate per ER
-- ============================================================================

create table public.seller (
    seller_id uuid primary key references auth.users(id) on delete cascade,
    username text not null unique,
    name text not null,
    email text,
    phone text,
    places text
);

create table public.buyer (
    buyer_id uuid primary key references auth.users(id) on delete cascade,
    username text not null unique,
    name text not null,
    email text,
    phone text,
    address text
);

-- ============================================================================
-- PRODUCT
-- ============================================================================

create table public.product (
    product_id int generated by default as identity primary key,
    product_name text not null,
    price numeric(10,2) not null check (price >= 0),
    image text,
    description text,
    category text,
    quantity int not null default 0 check (quantity >= 0),
    size text,
    color text,
    seller_id uuid not null references public.seller(seller_id) on delete cascade
);

-- ============================================================================
-- CART
-- ============================================================================

create table public.cart (
    cart_id uuid primary key default gen_random_uuid(),
    buyer_id uuid not null unique references public.buyer(buyer_id) on delete cascade
);

create table public.cart_item (
    cart_item_id int generated by default as identity primary key,
    quantity int not null check (quantity > 0),
    selected_color text,
    selected_size text,
    cart_id uuid not null references public.cart(cart_id) on delete cascade,
    product_id int not null references public.product(product_id) on delete cascade,
    unique (cart_id, product_id, selected_color, selected_size)
);

-- ============================================================================
-- ORDERS
-- ============================================================================

create table public.orders (
    order_id int generated by default as identity primary key,
    order_date timestamptz not null default now(),
    total_amount numeric(10,2) not null check (total_amount >= 0),
    status text not null default 'Pending' check (status in ('Pending','Paid','Shipped','Delivered')),
    buyer_id uuid not null references public.buyer(buyer_id) on delete cascade
);

create table public.order_item (
    order_item_id int generated by default as identity primary key,
    quantity int not null check (quantity > 0),
    price numeric(10,2) not null check (price >= 0),
    color text,
    size text,
    subtotal numeric(10,2) not null check (subtotal >= 0),
    order_id int not null references public.orders(order_id) on delete cascade,
    product_id int not null references public.product(product_id)
);

-- ============================================================================
-- CHAT
-- ============================================================================

create table public.conversations (
    id uuid primary key default gen_random_uuid(),
    buyer_id uuid not null references public.buyer(buyer_id) on delete cascade,
    seller_id uuid not null references public.seller(seller_id) on delete cascade,
    product_id int references public.product(product_id) on delete set null,
    created_at timestamptz not null default now(),
    unique (buyer_id, seller_id, product_id)
);

create table public.messages (
    id uuid primary key default gen_random_uuid(),
    conversation_id uuid not null references public.conversations(id) on delete cascade,
    sender_id uuid not null references auth.users(id) on delete cascade,
    content text not null,
    sent_at timestamptz not null default now()
);

-- ============================================================================
-- NOTIFICATIONS
-- ============================================================================

create table public.notifications (
    id uuid primary key default gen_random_uuid(),
    user_id uuid not null references auth.users(id) on delete cascade,
    type text not null,
    title text not null,
    content text,
    is_read boolean not null default false,
    created_at timestamptz not null default now()
);

create index if not exists idx_notifications_user on public.notifications (user_id, is_read);
create index if not exists idx_messages_conv on public.messages (conversation_id);
create index if not exists idx_product_seller on public.product (seller_id);
create index if not exists idx_product_category on public.product (category);


-- ============================================================================
-- NOTIFICATION TRIGGERS (server-side, bypass RLS)
-- ============================================================================

create or replace function public.notify_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if tg_table_name = 'order_item' then
        insert into public.notifications (user_id, type, title, content)
        select p.seller_id, 'order', 'มีออเดอร์ใหม่',
               'มีคำสั่งซื้อ #' || new.order_id || ' สำหรับสินค้า ' || p.product_name
        from public.product p
        where p.product_id = new.product_id;
        return new;
    elsif tg_table_name = 'orders' and old.status is distinct from new.status then
        insert into public.notifications (user_id, type, title, content)
        values (new.buyer_id, 'order_status',
                'สถานะคำสั่งซื้อ #' || new.order_id || ' อัปเดต',
                'สถานะเปลี่ยนเป็น ' || new.status);
        return new;
    end if;
    return new;
end;
$$;

drop trigger if exists trg_order_item_notify on public.order_item;
create trigger trg_order_item_notify
after insert on public.order_item
for each row execute function public.notify_user();

drop trigger if exists trg_orders_status_notify on public.orders;
create trigger trg_orders_status_notify
after update on public.orders
for each row execute function public.notify_user();


